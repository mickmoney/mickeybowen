  var center = 0;
  function layout() {
    items.forEach(function (el, i) {
      var rel = (i - center + items.length) % items.length;
      el.classList.remove('pos-center', 'pos-left', 'pos-right');
      if (rel === 0) el.classList.add('pos-center');
      else if (rel === 1) el.classList.add('pos-right');
      else el.classList.add('pos-left');
    });
  }
  layout();
  setInterval(function () {
    center = (center + 1) % items.length;
    layout();
  }, 2800);
})();
